param(
    [Parameter(Mandatory = $true)]
    [ValidateSet("Adb", "Hotspot")]
    [string]$Mode,

    [string]$HostAddress,
    [int]$Port = 8000,
    [switch]$ApplyAdbReverse
)

$repoRoot = Split-Path -Parent $PSScriptRoot
$envPath = Join-Path $repoRoot "apps\mobile\.env.local"

function Resolve-HotspotAddress {
    $addresses = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction Stop |
        Where-Object {
            $_.IPAddress -notlike "127.*" -and
            $_.IPAddress -notlike "169.254.*" -and
            $_.InterfaceAlias -notmatch "VMware|VirtualBox|Loopback"
        }

    $preferred = $addresses |
        Where-Object {
            $_.InterfaceAlias -match "Local Area Connection|Wi-Fi Direct|Hotspot"
        } |
        Select-Object -First 1

    if ($preferred) {
        return $preferred.IPAddress
    }

    $defaultInterface = Get-NetIPConfiguration |
        Where-Object { $_.IPv4DefaultGateway -ne $null } |
        Select-Object -First 1

    if ($defaultInterface -and $defaultInterface.IPv4Address) {
        return $defaultInterface.IPv4Address.IPAddress
    }

    return $null
}

if ($Mode -eq "Hotspot") {
    if (-not $HostAddress) {
        $HostAddress = Resolve-HotspotAddress
    }
    if (-not $HostAddress) {
        throw "Hotspot IPv4 was not detected. Pass -HostAddress explicitly."
    }
    $apiBaseUrl = "http://${HostAddress}:$Port"
} else {
    $apiBaseUrl = "http://127.0.0.1:$Port"
}

$content = @(
    "# Generated by scripts/use-mobile-network.ps1",
    "EXPO_PUBLIC_API_BASE_URL=$apiBaseUrl",
    "EXPO_PUBLIC_AUTH_MODE=formal"
) -join [Environment]::NewLine

Set-Content -LiteralPath $envPath -Value $content -Encoding utf8

if ($ApplyAdbReverse) {
    if ($Mode -ne "Adb") {
        throw "-ApplyAdbReverse can only be used with -Mode Adb."
    }
    & (Join-Path $PSScriptRoot "adb-reverse.ps1") -ApiPort $Port
}

Write-Host "Mobile API base URL: $apiBaseUrl"
Write-Host "Updated: $envPath"
Write-Host "Restart Metro and rebuild the APK after changing a build-time default."
Write-Host "A runtime override saved in My > Network & Connection takes precedence."
